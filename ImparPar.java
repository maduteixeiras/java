public class ImparPar {
    public static void main(String[] args) {
        System.out.println("Imprimindo números impares de 1 ate 51");
        for (int i = 1; i <= 50; i++) {
            if (i % 2 != 0) {
                System.out.println(i);
            }}
        
        System.out.println("Números pares de 52 até 100: ");
        for (int i = 52; i <= 100; i++) {
            if (i % 2 == 0) {
                System.out.println(i);
                
            }
        }
        }
    }
    

